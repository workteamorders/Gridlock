// Generates src/lib/gridlock-abi.ts from the compiled contract ABI.
// Source order: ../contracts/out (forge) then ../contracts/harness/build (solc-js). Run after any contract change.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'contracts');
const find = (name) => {
  const forge = join(root, 'out', `${name}.sol`, `${name}.json`);
  if (existsSync(forge)) return JSON.parse(readFileSync(forge, 'utf8')).abi;
  return JSON.parse(readFileSync(join(root, 'harness', 'build', `${name}.json`), 'utf8')).abi;
};
const abi = find('GridlockCars');
const out = `// GENERATED by scripts/sync-abi.mjs from the compiled GridlockCars ABI. Do not edit by hand.\nexport const carsAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'gridlock-abi.ts'), out);
console.log(`gridlock-abi.ts written (${abi.length} entries)`);
